import {
  existsSync,
  mkdirSync,
  readdirSync,
  readFileSync,
  writeFileSync,
} from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

import matter from 'gray-matter'
import { remark } from 'remark'
import html from 'remark-html'

const SLUG_PATTERN = /^[a-z0-9-]+$/
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(scriptDir, '..')
const blogDir = path.join(projectRoot, 'src/content/blog')
const manifestPath = path.join(blogDir, 'manifest.ts')
const shouldCheckManifest = process.argv.includes('--check')

function requireStringField(frontmatter, fieldName, slug) {
  const value = frontmatter[fieldName]

  if (typeof value !== 'string' || !value.trim()) {
    throw new Error(
      `Blog post "${slug}" is missing required frontmatter field "${fieldName}"`
    )
  }

  return value.trim()
}

function requireDateField(frontmatter, slug) {
  const value = frontmatter.date
  const date =
    value instanceof Date && !Number.isNaN(value.getTime())
      ? value.toISOString().slice(0, 10)
      : typeof value === 'string'
        ? value.trim()
        : ''

  if (!DATE_PATTERN.test(date)) {
    throw new Error(
      `Blog post "${slug}" must use a YYYY-MM-DD frontmatter date`
    )
  }

  const parsedDate = new Date(`${date}T00:00:00.000Z`)
  if (
    Number.isNaN(parsedDate.getTime()) ||
    parsedDate.toISOString().slice(0, 10) !== date
  ) {
    throw new Error(`Blog post "${slug}" has an invalid frontmatter date`)
  }

  return date
}

function requireTagsField(frontmatter, slug) {
  const tags = frontmatter.tags
  let parsedTags = []

  if (Array.isArray(tags)) {
    if (!tags.every((tag) => typeof tag === 'string')) {
      throw new Error(
        `Blog post "${slug}" frontmatter field "tags" must contain strings`
      )
    }

    parsedTags = tags.map((tag) => tag.trim()).filter(Boolean)
  } else if (typeof tags === 'string') {
    parsedTags = tags
      .split(',')
      .map((tag) => tag.trim())
      .filter(Boolean)
  }

  if (parsedTags.length === 0) {
    throw new Error(
      `Blog post "${slug}" is missing required frontmatter field "tags"`
    )
  }

  return parsedTags
}

function parsePost(fileName) {
  const slug = fileName.replace(/\.md$/, '')

  if (!SLUG_PATTERN.test(slug)) {
    throw new Error(
      `Blog post file "${fileName}" must use a lowercase kebab-case slug`
    )
  }

  const source = readFileSync(path.join(blogDir, fileName), 'utf8')
  const { content, data } = matter(source)
  const contentHtml = remark().use(html).processSync(content).toString()

  return {
    slug,
    title: requireStringField(data, 'title', slug),
    description: requireStringField(data, 'description', slug),
    date: requireDateField(data, slug),
    tags: requireTagsField(data, slug),
    contentHtml,
  }
}

function buildManifest() {
  mkdirSync(blogDir, { recursive: true })

  const posts = existsSync(blogDir)
    ? readdirSync(blogDir)
        .filter((fileName) => fileName.endsWith('.md'))
        .sort()
        .map(parsePost)
    : []
  const seenSlugs = new Set()

  for (const post of posts) {
    if (seenSlugs.has(post.slug)) {
      throw new Error(`Duplicate blog post slug "${post.slug}"`)
    }

    seenSlugs.add(post.slug)
  }

  return [
    '// This file is generated by scripts/generate-blog-manifest.mjs.',
    '// Do not edit by hand; edit Markdown files in this directory instead.',
    '',
    'export type BlogPostManifestEntry = {',
    '  slug: string',
    '  title: string',
    '  description: string',
    '  date: string',
    '  tags: string[]',
    '  contentHtml: string',
    '}',
    '',
    '// prettier-ignore',
    `export const blogPosts: BlogPostManifestEntry[] = ${JSON.stringify(
      posts,
      null,
      2
    )}`,
    '',
  ].join('\n')
}

const manifest = buildManifest()
const previousManifest = existsSync(manifestPath)
  ? readFileSync(manifestPath, 'utf8')
  : null

if (previousManifest !== manifest) {
  if (shouldCheckManifest) {
    throw new Error(
      'Blog manifest is out of date. Run npm run generate:blog and commit the result.'
    )
  }

  writeFileSync(manifestPath, manifest)
}
